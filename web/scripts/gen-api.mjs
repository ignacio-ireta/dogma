#!/usr/bin/env node
// Regenerates the browser's API contract from the local API (ENGINEERING_STANDARDS §7).
//
//   pnpm gen:api          write src/api/openapi.json and src/api/schema.d.ts
//   pnpm gen:api --check  exit 1 when either committed file is stale (used by `make check`)
//
// The OpenAPI document is exported in-process by the Python app, so no server runs and nothing
// listens on a port. The types are never written by hand. The check regenerates both outputs in
// memory and compares them with the committed files.

import { execFile } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const WEB_DIR = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const REPO_DIR = resolve(WEB_DIR, "..");
const SPEC_PATH = resolve(WEB_DIR, "src/api/openapi.json");
const TYPES_PATH = resolve(WEB_DIR, "src/api/schema.d.ts");

const EXPORT_SCRIPT = [
  "import json",
  "from dogma.api.app import create_app",
  "from dogma.core.config import Settings",
  "print(json.dumps(create_app(Settings()).openapi(), indent=2, sort_keys=True))",
].join("\n");

const TYPES_HEADER =
  "// Generated by web/scripts/gen-api.mjs from the local API's OpenAPI document. Do not edit.\n";

function exportSpec() {
  return new Promise((resolvePromise, reject) => {
    execFile(
      "uv",
      ["run", "--frozen", "python", "-c", EXPORT_SCRIPT],
      { cwd: REPO_DIR, maxBuffer: 64 * 1024 * 1024 },
      (error, stdout, stderr) => {
        if (error) {
          reject(new Error(`could not export the OpenAPI document: ${stderr || error.message}`));
          return;
        }
        resolvePromise(stdout);
      },
    );
  });
}

async function generateTypes(specText) {
  const ast = await openapiTS(JSON.parse(specText));
  return `${TYPES_HEADER}${astToString(ast)}`;
}

async function readOrEmpty(path) {
  try {
    return await readFile(path, "utf8");
  } catch (error) {
    if (error && error.code === "ENOENT") {
      return "";
    }
    throw error;
  }
}

async function main() {
  const check = process.argv.includes("--check");
  const specText = await exportSpec();
  const typesText = await generateTypes(specText);

  if (check) {
    const staleSpec = (await readOrEmpty(SPEC_PATH)) !== specText;
    const staleTypes = (await readOrEmpty(TYPES_PATH)) !== typesText;
    if (staleSpec || staleTypes) {
      const stale = [staleSpec && "src/api/openapi.json", staleTypes && "src/api/schema.d.ts"]
        .filter(Boolean)
        .join(", ");
      process.stderr.write(
        `API types are stale: ${stale}. Run \`pnpm gen:api\` and commit the result.\n`,
      );
      process.exitCode = 1;
      return;
    }
    process.stdout.write("API types are up to date.\n");
    return;
  }

  await writeFile(SPEC_PATH, specText, "utf8");
  await writeFile(TYPES_PATH, typesText, "utf8");
  process.stdout.write("Wrote src/api/openapi.json and src/api/schema.d.ts.\n");
}

main().catch((error) => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 1;
});
