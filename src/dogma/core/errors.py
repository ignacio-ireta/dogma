class DogmaError(Exception):
    """Base class: carries a stable ``code`` and a learner-safe ``message``."""

    def __init__(self, code: ErrorCode, message: str) -> None:
        super().__init__(f"[{code}] {message}")
        self.code = code
        self.message = message


class ContentError(DogmaError):
    """A content package or the syllabus is missing, malformed, or inconsistent."""


class RunnerError(DogmaError):
    """The sandboxed run failed for infrastructure reasons (not because learner code is wrong)."""
